interface I18nContextType {
  lang: SupportedLang;
  setLang: (lang: SupportedLang) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
  languages: typeof SUPPORTED_LANGUAGES;
}

const I18nContext = createContext<I18nContextType>({
  lang: 'zh',
  setLang: () => {},
  t: (key) => key,
  languages: SUPPORTED_LANGUAGES,
});

function getInitialLang(): SupportedLang {
  try {
    const saved = localStorage.getItem('akasha:lang') as SupportedLang;
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch { /* ignore */ }

  try {
    const nav = (navigator.language || '').toLowerCase();
    if (nav.startsWith('zh')) return 'zh';
    if (nav.startsWith('ja')) return 'ja';
    if (nav.startsWith('fr')) return 'fr';
    if (nav.startsWith('de')) return 'de';
    if (nav.startsWith('ko')) return 'ko';
    if (nav.startsWith('ru')) return 'ru';
    if (nav.startsWith('hi')) return 'hi';
  } catch { /* ignore */ }

  // Final fallback aligned with launcher_i18n.resolve_lang(): neutral English
  // when neither a saved preference nor the browser locale matches.
  return 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<SupportedLang>(getInitialLang);

  useEffect(() => {
    try {
      document.documentElement.lang = lang;
    } catch { /* ignore */ }
  }, [lang]);

  const setLang = useCallback((newLang: SupportedLang) => {
    setLangState(newLang);
    try {
      localStorage.setItem('akasha:lang', newLang);
    } catch { /* ignore */ }
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>): string => {
      const dict = TRANSLATIONS[lang] || TRANSLATIONS.zh;
      let text = dict[key] || TRANSLATIONS.zh[key] || key;
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        }
      }
      return text;
    },
    [lang]
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t, languages: SUPPORTED_LANGUAGES }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
